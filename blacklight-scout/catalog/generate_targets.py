#!/usr/bin/env python3
"""Generate Scout target tables from blacklight-scout/catalog/targets.json."""

from __future__ import annotations

import json
from pathlib import Path

CATALOG_DIR = Path(__file__).resolve().parent
TARGETS_JSON = CATALOG_DIR / "targets.json"
C_HEADER_OUT = CATALOG_DIR / "static_targets_generated.h"
CS_TARGETS_OUT = CATALOG_DIR.parent / "managed" / "GeneratedTargets.cs"
REPO_ROOT = CATALOG_DIR.parents[1]
ARTIFACTS_JSON = REPO_ROOT / "blacklight-rules" / "catalog" / "confirmed_artifacts.json"
MATRIX_OUT = REPO_ROOT / "docs" / "matrix.md"


def relative_pattern(pattern: str, home_var: str) -> str:
    return normalize_pattern_for_python(pattern).removeprefix(home_var + "/")


def render_matrix(catalog: dict, artifacts_catalog: dict) -> str:
    """Render declared coverage without treating catalog entries as runtime proof."""
    platforms = ["windows", "darwin", "linux"]
    targets = {
        platform: {
            (target["tool"], target["family"], relative_pattern(target["pattern"], profile["home_var"]))
            for target in profile["targets"]
        }
        for platform, profile in catalog["platforms"].items()
    }
    artifacts = artifacts_catalog["artifacts"]
    tools = sorted(set(catalog["tools"]) | {item["tool"] for item in artifacts})
    families = sorted({family for entries in targets.values() for _, family, _ in entries}
                      | {item["family"] for item in artifacts})
    lines = [
        "<!-- Generated by blacklight-scout/catalog/generate_targets.py. Do not edit by hand. -->",
        "# Agent and CLI collection matrix", "",
        "Sources: [Scout targets](../blacklight-scout/catalog/targets.json) and "
        "[confirmed artifacts](../blacklight-rules/catalog/confirmed_artifacts.json).", "",
        "Scout collects paths, filesystem metadata, and allowlisted count-only metadata. "
        "It does not transfer files or read session bodies. Operators select and download "
        "session artifacts for Python analysis. Listed coverage is catalog-declared, not runtime validation.", "",
        "Windows executable inspection may read allowlisted non-session metadata; "
        "BOF and POSIX libraries use filesystem metadata. Grok content inspection is deferred "
        "in Scout; Devin, Strands, Kiro, OpenCode, and Muse Code are existence/path enumeration only. "
        "See [architecture](architecture.md) for current parser support and limits.", "",
        "## Agent coverage", "",
        "Static targets count exact catalog entries, including directories; they are not collected-file counts.", "",
        "| Agent / CLI ID | Windows targets | macOS targets | Linux targets | Confirmed artifacts |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for tool in tools:
        counts = [sum(entry[0] == tool for entry in targets[p]) for p in platforms]
        lines.append(f"| `{tool}` | " + " | ".join(str(count) for count in counts)
                     + f" | {sum(item['tool'] == tool for item in artifacts)} |")
    lines.extend(["", "## Artifact families", "",
                  "A check means at least one Scout target or confirmed artifact is cataloged for that family.", "",
                  "| Agent / CLI ID | " + " | ".join(families) + " |",
                  "| --- | " + " | ".join("---" for _ in families) + " |"])
    for tool in tools:
        present = {family for entries in targets.values() for entry_tool, family, _ in entries if entry_tool == tool}
        present.update(item["family"] for item in artifacts if item["tool"] == tool)
        lines.append(f"| `{tool}` | " + " | ".join("Yes" if family in present else "—" for family in families) + " |")
    lines.extend(["", "## Collection detail", "",
                  "Paths are relative to the user's home directory. Platform columns show exact static "
                  "Scout targets only; a dash does not exclude bounded descendant discovery. "
                  "Wildcards are catalog patterns, not a promise to collect every match.", ""])
    for state, description in artifacts_catalog["assessment_coverage_states"].items():
        lines.append(f"- `{state}`: {description}")
    lines.extend(["", "Evidence abbreviations: **S** = static Scout catalog; **E** = endpoint count-only "
                  "assessment; **A** = session-analysis evidence. These are the artifact catalog's "
                  "evidence references, not exhaustive parser support (for example, Grok chat parsing "
                  "is documented in architecture).", ""])
    evidence_labels = {"blacklight.scout.PATH_TARGETS": "S",
                       "blacklight.scout.endpoint_assessment": "E",
                       "blacklight.analyze.run_session_detail": "A"}
    for tool in tools:
        lines.extend([f"### {tool}", "",
                      "| Artifact / path | Family | Kind | Windows | macOS | Linux | Assessment coverage | Evidence |",
                      "| --- | --- | --- | --- | --- | --- | --- | --- |"])
        by_key = {(item["family"], item["relative_path"]): item for item in artifacts if item["tool"] == tool}
        keys = set(by_key) | {(family, path) for entries in targets.values()
                             for entry_tool, family, path in entries if entry_tool == tool}
        for family, path in sorted(keys):
            item = by_key.get((family, path), {})
            present = ["Yes" if (tool, family, path) in targets[p] else "—" for p in platforms]
            evidence = ", ".join(evidence_labels.get(ref, ref) for ref in item.get("confirmed_by", [])) or "—"
            coverage = item.get("assessment_coverage", "static target; not in artifact catalog")
            safe_path = path.replace("|", "&#124;")
            lines.append(f"| `{safe_path}` | {family} | {item.get('path_kind', 'unspecified')} | "
                         + " | ".join(present) + f" | {coverage} | {evidence} |")
        lines.append("")
    lines.extend(["## Regenerate", "", "```bash",
                  "uv run --locked python blacklight-scout/catalog/generate_targets.py", "```", "",
                  "Edit the source catalogs, then regenerate. This command also refreshes the native "
                  "and managed Scout target tables.", ""])
    return "\n".join(lines)


def load_catalog() -> dict:
    return json.loads(TARGETS_JSON.read_text(encoding="utf-8"))


def normalize_pattern_for_python(pattern: str) -> str:
    return pattern.replace("\\", "/")


def pattern_to_c_windows(pattern: str) -> str:
    normalized = normalize_pattern_for_python(pattern)
    escaped = normalized.replace("\\", "\\\\")
    return f'L"{escaped}"'


def pattern_to_c_posix(pattern: str) -> str:
    return f'"{normalize_pattern_for_python(pattern)}"'


def render_c_header(catalog: dict) -> str:
    lines = [
        "/* Auto-generated from blacklight-scout/catalog/targets.json. Do not edit by hand. */",
        "#ifndef BLACKLIGHT_STATIC_TARGETS_GENERATED_H",
        "#define BLACKLIGHT_STATIC_TARGETS_GENERATED_H",
        "",
        '#include "ai_path_scout_core.h"',
        "",
    ]

    def append_target_table(targets: list[dict], *, windows: bool) -> None:
        lines.append("static const bl_path_target_t BL_STATIC_TARGETS[] = {")
        for target in targets:
            pattern = pattern_to_c_windows(target["pattern"]) if windows else pattern_to_c_posix(target["pattern"])
            lines.append(f'    {{ "{target["tool"]}", "{target["family"]}", {pattern} }},')
        lines.append("};")

    windows_targets = catalog["platforms"]["windows"]["targets"]
    darwin_targets = catalog["platforms"]["darwin"]["targets"]
    linux_targets = catalog["platforms"]["linux"]["targets"]

    lines.append("#ifdef BLACKLIGHT_SCOUT_WINDOWS")
    append_target_table(windows_targets, windows=True)
    lines.append("#elif defined(__APPLE__)")
    append_target_table(darwin_targets, windows=False)
    lines.append("#else")
    append_target_table(linux_targets, windows=False)
    lines.append("#endif")
    lines.append("")
    lines.append("#define BL_STATIC_TARGETS_COUNT (sizeof(BL_STATIC_TARGETS) / sizeof(BL_STATIC_TARGETS[0]))")
    lines.append("")
    lines.append("#endif")
    lines.append("")
    return "\n".join(lines)


def csharp_string(value: str) -> str:
    return (
        value
        .replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
    )


def render_csharp_targets(catalog: dict) -> str:
    windows_targets = catalog["platforms"]["windows"]["targets"]
    lines = [
        "// Auto-generated from blacklight-scout/catalog/targets.json. Do not edit by hand.",
        "namespace Blacklight.Scout.Managed",
        "{",
        "    internal static class GeneratedTargets",
        "    {",
        "        internal static readonly Target[] Windows = new Target[]",
        "        {",
    ]
    for target in windows_targets:
        lines.append(
            '            new Target("{tool}", "{family}", "{pattern}"),'.format(
                tool=csharp_string(target["tool"]),
                family=csharp_string(target["family"]),
                pattern=csharp_string(target["pattern"]),
            )
        )
    lines.extend(
        [
            "        };",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    catalog = load_catalog()
    C_HEADER_OUT.write_text(render_c_header(catalog), encoding="utf-8")
    CS_TARGETS_OUT.parent.mkdir(parents=True, exist_ok=True)
    CS_TARGETS_OUT.write_text(render_csharp_targets(catalog), encoding="utf-8")
    artifacts_catalog = json.loads(ARTIFACTS_JSON.read_text(encoding="utf-8"))
    MATRIX_OUT.parent.mkdir(parents=True, exist_ok=True)
    MATRIX_OUT.write_text(render_matrix(catalog, artifacts_catalog), encoding="utf-8")
    print(f"Wrote {C_HEADER_OUT}")
    print(f"Wrote {CS_TARGETS_OUT}")
    print(f"Wrote {MATRIX_OUT}")


if __name__ == "__main__":
    main()
